"""LLM transform configuration: a template whose loops nest too deeply is a validation error naming its position.

Before the change the builtin ``SyntaxError`` from Python's compiler passed
through every validator (pydantic converts only ``ValueError``), so building the
configuration raised it bare. Inputs are generated by loops; expected texts are
spelled here so the file collects on the tree before the change.
"""

from __future__ import annotations

import pytest
from pydantic import ValidationError

from elspeth.contracts.schema import SchemaConfig
from elspeth.plugins.transforms.llm.base import LLMConfig

_OBSERVED = SchemaConfig(mode="observed", fields=None)


def _nested_loops(levels: int) -> str:
    return "Rate {{ row.review }}. " + "{% for item in [1] %}" * levels + "x" + "{% endfor %}" * levels


def _refusal(position: str) -> str:
    return f"{position} is too deeply nested to compile: its loops or blocks nest deeper than Python allows. Flatten the nesting."


def _config(**options: object) -> LLMConfig:
    return LLMConfig(provider="azure", schema_config=_OBSERVED, required_input_fields=["review"], **options)


def test_twenty_nested_loops_are_admitted() -> None:
    _config(prompt_template=_nested_loops(20))


def test_node_prompt_nested_too_deeply_names_its_position() -> None:
    with pytest.raises(ValidationError) as raised:
        _config(prompt_template=_nested_loops(21))

    assert [str(error["msg"]) for error in raised.value.errors()] == [f"Value error, {_refusal('prompt_template')}"]


@pytest.mark.parametrize("form", ["mapping", "list"])
def test_query_template_nested_too_deeply_names_the_query(form: str) -> None:
    query = {"input_fields": {"review": "review"}, "template": _nested_loops(21)}
    queries: object = {"tone": query} if form == "mapping" else [{"name": "tone", **query}]

    with pytest.raises(ValidationError) as raised:
        _config(prompt_template="Rate {{ row.review }}.", queries=queries)

    assert _refusal("queries.tone.template") in str(raised.value)
