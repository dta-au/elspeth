"""Ordered dependencies are explicit and never become upstream requirements."""

from typing import Any

import pytest
from pydantic import ValidationError

from elspeth.plugins.transforms.llm.base import LLMConfig


def ordered_options() -> dict[str, Any]:
    return {
        "provider": "azure",
        "schema": {"mode": "observed"},
        "query_input_mode": "ordered",
        "pool_size": 1,
        "required_input_fields": ["text"],
        "response_field": "answer",
        "queries": [
            {
                "name": "extract",
                "input_fields": {"text": "text"},
                "template": "{{ row.text }}",
                "output_fields": [{"suffix": "score", "type": "integer"}],
            },
            {"name": "assess", "input_fields": {"score": "extract_score"}, "template": "{{ row.score }}"},
        ],
    }


def test_prior_generated_binding_does_not_require_an_upstream_field() -> None:
    config = LLMConfig.model_validate(ordered_options())
    assert config.declared_input_fields == frozenset({"text"})


@pytest.mark.parametrize("field", ["extract_score", "extract_answer", "extract_answer_model", "extract_answer_usage"])
def test_all_prior_generated_field_families_can_bind(field: str) -> None:
    options = ordered_options()
    options["queries"][1]["input_fields"] = {"value": field}
    options["queries"][1]["template"] = "{{ row.value }}"
    LLMConfig.model_validate(options)


@pytest.mark.parametrize("field", ["extract_score", "assess_answer"])
def test_self_and_forward_references_refused(field: str) -> None:
    options = ordered_options()
    options["queries"][0]["input_fields"] = {"text": field}
    with pytest.raises(ValidationError, match="earlier query"):
        LLMConfig.model_validate(options)


def test_ordered_requires_list_and_sequential_pool() -> None:
    options = ordered_options()
    options["pool_size"] = 2
    with pytest.raises(ValidationError, match="pool_size=1"):
        LLMConfig.model_validate(options)
    options["pool_size"] = 1
    options["queries"] = {q["name"]: q for q in options["queries"]}
    with pytest.raises(ValidationError, match="list"):
        LLMConfig.model_validate(options)


def test_upstream_default_still_rejects_dependent_bindings() -> None:
    options = ordered_options()
    del options["query_input_mode"]
    with pytest.raises(ValidationError, match="generated by this node"):
        LLMConfig.model_validate(options)


def test_constant_first_query_needs_no_fabricated_external_requirement() -> None:
    options = ordered_options()
    options.pop("required_input_fields")
    options["queries"][0]["input_fields"] = {}
    options["queries"][0]["template"] = "Return five"
    config = LLMConfig.model_validate(options)
    assert config.declared_input_fields == frozenset()


def test_complete_output_inventory_rejects_typed_raw_collision() -> None:
    options = ordered_options()
    options["queries"][0]["output_fields"] = [{"suffix": "answer", "type": "string"}]
    with pytest.raises(ValidationError, match="collision"):
        LLMConfig.model_validate(options)


def test_generated_source_row_read_refused() -> None:
    options = ordered_options()
    options["required_input_fields"] = []
    options["queries"][1]["template"] = "{{ row.source_row.extract_score }}"
    with pytest.raises(ValidationError, match="generated"):
        LLMConfig.model_validate(options)


@pytest.mark.parametrize("path", ["required", "schema", "image", "image_format"])
def test_ordered_generated_fields_cannot_be_original_only_inputs(path: str) -> None:
    options = ordered_options()
    if path == "required":
        options["required_input_fields"].append("extract_score")
    elif path == "schema":
        options["schema"]["required_fields"] = ["extract_score"]
    elif path == "image":
        options["image_inputs"] = [{"field": "extract_score", "format": "png"}]
    else:
        options["image_inputs"] = [{"field": "photo", "format_field": "extract_score", "required": False}]
    with pytest.raises(ValidationError, match=r"generated.*original row"):
        LLMConfig.model_validate(options)


def test_header_spelling_of_generated_binding_is_ambiguous_not_an_external_requirement() -> None:
    options = ordered_options()
    options["queries"][1]["input_fields"] = {"score": "Extract Score"}
    with pytest.raises(ValidationError, match="ambiguously"):
        LLMConfig.model_validate(options)


def test_ordered_yaml_roundtrip_keeps_list_order_and_empty_bindings() -> None:
    import yaml

    options = ordered_options()
    options["required_input_fields"] = []
    options["queries"][0]["input_fields"] = {}
    options["queries"][0]["template"] = "Return five"
    serialized = LLMConfig.model_validate(options).model_dump(mode="json", by_alias=True)
    reloaded = LLMConfig.model_validate(yaml.safe_load(yaml.safe_dump(serialized)))
    assert [spec.name for spec in reloaded.resolved_queries()] == ["extract", "assess"]
    assert reloaded.resolved_queries()[0].input_fields == {}
    assert reloaded.required_input_fields == []


@pytest.mark.parametrize("suffix", ["b_answer", "b_answer_model", "b_answer_usage"])
def test_cross_query_typed_operational_collision_refused(suffix: str) -> None:
    options = ordered_options()
    options["queries"][0].update(name="a", output_fields=[{"suffix": suffix, "type": "string"}])
    options["queries"][1].update(name="a_b", input_fields={"score": "text"})
    with pytest.raises(ValidationError, match="collision"):
        LLMConfig.model_validate(options)
