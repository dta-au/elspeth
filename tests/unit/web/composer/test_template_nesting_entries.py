"""Template text nested too deeply reaches the user as a validation entry, through the real entry functions.

Before the change:

- more than 20 nested loops raised a builtin ``SyntaxError`` out of
  ``CompositionState.validate()``, execution validation and ``compose()``;
- a deep expression chain, or an inline prompt over the byte bound, raised out
  of the advisor's pipeline summary, and the advisor checkpoint ended the turn.

Inputs are generated by loops, with neutral names. Expected texts are spelled
here so the file collects on the tree before the change.
"""

