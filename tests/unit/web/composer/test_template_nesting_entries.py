from tests.unit.web.composer.test_tools import execute_tool

__all__ = ["make_service"]  # the advisor checkpoint fixture, used by name below

LIMIT = 64 * 1024
NESTED = "Rate {{ row.review }}. " + "{% for item in [1] %}" * 21 + "x" + "{% endfor %}" * 21
CHAIN = "Rate {{ row.review }}. {{ 1" + "+1" * 1500 + " }}"
OVER_BOUND = "Rate {{ row.review }}. " + "x" * LIMIT
UNKNOWN_LINE = "named row field references: UNKNOWN (the prompt could not be analysed)"


def _nesting_refusal(position: str) -> str:
    return f"{position} is too deeply nested to compile: its loops or blocks nest deeper than Python allows. Flatten the nesting."


def _query_state(tmp_path: Path, template: object) -> tuple[Any, Any]:
    return _state(
        tmp_path,
        prompt_template=None,
        options={"queries": [{**_QUERY, "template": template}], "max_capacity_retry_seconds": 30},
        without=("prompt_template", "response_field"),
    )


# ---------------------------------------------------------------- authoring validation


def test_authoring_validation_names_the_step_and_query_for_nested_loops(tmp_path: Path) -> None:
    _session_id, state = _query_state(tmp_path, NESTED)

    summary = state.validate()

    entry = next(entry for entry in summary.errors if entry.error_code == "plugin_options_invalid")
    assert entry.component == "node:classify"
    assert entry.message == _nesting_refusal("queries.q1.template")


def test_authoring_validation_names_the_query_over_the_byte_bound(tmp_path: Path) -> None:
    _session_id, state = _query_state(tmp_path, OVER_BOUND)

    entry = next(entry for entry in state.validate().errors if entry.error_code == "plugin_options_invalid")

    assert entry.message.startswith(f"queries.q1.template is {len(OVER_BOUND)} bytes; the limit for one prompt template is {LIMIT} bytes.")


def test_other_query_option_errors_keep_the_generic_sentence(tmp_path: Path) -> None:
    _session_id, state = _query_state(tmp_path, "Rate {{ row.review ")

    entry = next(entry for entry in state.validate().errors if entry.error_code == "plugin_options_invalid")

    assert entry.message.startswith("Invalid multi-query options.")


# ---------------------------------------------------------------- execution validation (runtime preflight, run admission)


def test_execution_validation_refuses_a_nested_file_prompt_by_position(tmp_path: Path) -> None:
    """An inline prompt reaches the same plugin validator once its review card is accepted (plugin tests pin that)."""
    session_id, state = _state(tmp_path, prompt_template=_marker(NESTED))

    result = _execution_validate(tmp_path, session_id, state, NESTED)

    assert not result.is_valid
    (error,) = result.errors
    assert _nesting_refusal("prompt_template") in error.message
    assert "internally" not in error.message


# ---------------------------------------------------------------- the advisor's pipeline summary and checkpoint


@pytest.mark.parametrize("text", [CHAIN, OVER_BOUND], ids=["deep-chain", "over-the-byte-bound"])
def test_advisor_summary_says_the_prompt_could_not_be_analysed(tmp_path: Path, text: str) -> None:
    _session_id, state = _state(tmp_path, prompt_template=text)

    summary = summarize_pipeline_for_advisor(state)

    assert UNKNOWN_LINE in summary


@pytest.mark.parametrize("text", [CHAIN, OVER_BOUND], ids=["deep-chain", "over-the-byte-bound"])
def test_advisor_summary_says_so_for_a_file_the_composer_wrote(tmp_path: Path, text: str) -> None:
    """The advisor is sent the whole text of a file the composer wrote, and a file may be larger than one template."""
    marker = _marker(text)
    _session_id, state = _state(tmp_path, prompt_template=marker)
    reference = inline_content_reference(marker)
    assert reference is not None
    sent_file = AdvisorPromptFile(filename="prompt.txt", size_bytes=len(text.encode()), author="composer", text=text)
    prompt_files = AdvisorPromptFiles(files={prompt_file_key(reference): sent_file}, read=True)

    summary = summarize_pipeline_for_advisor(state, prompt_files)

    assert UNKNOWN_LINE in summary


@pytest.mark.asyncio
@pytest.mark.parametrize("text", [CHAIN, OVER_BOUND], ids=["deep-chain", "over-the-byte-bound"])
async def test_advisor_checkpoint_reviews_a_pipeline_whose_prompt_cannot_be_analysed(make_service: Any, tmp_path: Path, text: str) -> None:
    _session_id, state = _state(tmp_path, prompt_template=text)
    service = make_service()
    service._advisor_checkpoint._call_advisor_with_audit = _AsyncRecorder(return_value=(_checkpoint_reply(), {}))

    verdict = await service._advisor_checkpoint._run_advisor_checkpoint(
        phase="early", state=state, **_fenced_session(service), recorder=make_recorder()
    )

    assert verdict.ok, verdict.findings_text
    sent = service._advisor_checkpoint._call_advisor_with_audit.call_args.args[0]
    assert UNKNOWN_LINE in sent["schema_excerpt"]


# ---------------------------------------------------------------- tool calls that write the text


def test_patching_nested_loops_into_a_prompt_is_a_refused_tool_call() -> None:
    state = _approved_state()

    result = execute_tool("patch_node_options", {"node_id": "code_themes", "patch": {"prompt_template": NESTED}}, state, _mock_catalog())

    assert not result.success
    assert _nesting_refusal("prompt_template") in repr(result.to_dict())


def test_editing_nested_loops_into_a_prompt_is_a_refused_tool_call() -> None:
    state = _approved_state()
    text = state.nodes[0].options["prompt_template"]
    args = {
        "target": {"kind": "node_option", "node_id": "code_themes", "option": "prompt_template"},
        "expected_sha256": sha256(text.encode("utf-8")).hexdigest(),
        "expected_state_id": "state-1",
        "edits": [{"old": "Classify", "replacement": NESTED, "replace_all": False}],
    }

    result = execute_tool("change_substring", args, state, _mock_catalog(), current_state_id="state-1")

    assert not result.success
    assert result.updated_state is None or result.updated_state is state


# ---------------------------------------------------------------- a composer turn over a saved state


@pytest.mark.asyncio
async def test_a_turn_over_saved_nested_loops_reaches_the_planner(monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> None:
    from elspeth.web.composer.availability import ComposerAvailability

    def _available(*, model: str, **_kwargs: object) -> ComposerAvailability:
        return ComposerAvailability(available=True, model=model, provider="test")

    monkeypatch.setattr("elspeth.web.composer.service.compute_availability", _available)
    monkeypatch.setattr(AdvisorCheckpointOwner, "_run_advisor_checkpoint", _clean_advisor_checkpoint, raising=True)
    _session_id, state = _query_state(tmp_path, NESTED)
    service, session_id = _composer_service_with_session(catalog=_mock_catalog(), settings=_make_settings(data_dir=tmp_path))

    with patch("litellm.acompletion", new_callable=AsyncMock, return_value=_make_llm_response(content="Done.")) as completion:
        result = await service.compose("Check the pipeline", [], state, session_id=session_id)

    assert completion.await_count >= 1, "the planner was reached"
    entries = [(entry.component, entry.message) for entry in result.state.validate().errors]
    assert ("node:classify", _nesting_refusal("queries.q1.template")) in entries
    assert "internally" not in result.message
