"""A saved state holding template text the plugin would refuse still opens and still takes a composer turn.

Three inputs, each the first query template of one llm step, generated by loops:

- 21 nested loops: Python's compiler refuses Jinja's generated code with a
  builtin ``SyntaxError``;
- a 241-term expression chain: the field analysis recursed until
  ``RecursionError``;
- an inline template over the 64 KiB byte bound.

Two ways such text is already saved, neither of which validates templates:
YAML import (deliberately not refused, a separate decision), and an older
saved state written straight into the session store (the customer's existing
sessions). Before the change ``GET state`` answered an untyped 500 for the
nested loops, and a composer turn ended with a bare exception (nested loops
at validation; the chain and the oversized text at the end-of-turn advisor
check). Now ``GET state`` is 200 with a validation entry naming the step, and
the turn completes with the real end-of-turn checkpoint, whose evidence says
the prompt could not be analysed where that is so.

In-process ASGI client and the repository's own composer job runner; only the
provider SDK call is scripted. Expected texts are spelled here so the file
collects on the tree before the change.
"""

