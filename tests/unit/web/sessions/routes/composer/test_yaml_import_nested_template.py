LIMIT = 64 * 1024
NESTED = "Rate {{ row.text }}. " + "{% for item in [1] %}" * 21 + "x" + "{% endfor %}" * 21
CHAIN = "Rate {{ row.text }}. {{ 1" + "+1" * 241 + " }}"
OVER_BOUND = "Rate {{ row.text }}. " + "x" * LIMIT
UNKNOWN_LINE = "named row field references: UNKNOWN (the prompt could not be analysed)"

INPUTS = {
    "nested-loops": (
        NESTED,
        "queries.q1.template is too deeply nested to compile: its loops or blocks nest deeper than Python allows. Flatten the nesting.",
    ),
    "deep-chain": (CHAIN, "Invalid multi-query options."),
    "over-the-byte-bound": (
        OVER_BOUND,
        f"queries.q1.template is {len(OVER_BOUND)} bytes; the limit for one prompt template is {LIMIT} bytes.",
    ),
}

_QUERY_OUTPUTS = [{"suffix": "score", "type": "integer"}]


def _profile_app(tmp_path: Path) -> tuple[Any, Any]:
    """The session-route app with the llm plugin turned on through one operator profile."""
    app, sessions = _make_app(tmp_path)
    settings = WebSettings.model_validate(
        {
            "data_dir": tmp_path,
            "composer_max_composition_turns": 15,
            "composer_context_max_prompt_tokens": 200_000,
            "composer_max_discovery_turns": 10,
            "composer_timeout_seconds": 85.0,
            "composer_rate_limit_per_minute": 10,
            "composer_prompt_guard_mode": "debug-when-unconfigured",
            "shareable_link_signing_key": b"\x00" * 32,
            "llm_profiles": {
                "text-model": {
                    "provider": "openrouter",
                    "model": "openai/gpt-5-mini",
                    "credential_scope": "server",
                    "credential_ref": "PROFILE_TEST_KEY",
                }
            },
            "default_llm_profile": "text-model",
        }
    )
    runtime = RuntimeWebPluginConfig.from_settings(settings)
    policy = compile_web_plugin_policy(registry=get_shared_plugin_manager(), settings=runtime)
    catalog = create_catalog_service()
    unrestricted = PluginAvailabilitySnapshot.for_trained_operator(catalog)
    snapshot = PluginAvailabilitySnapshot.create(
        policy_hash=policy.policy_hash,
        principal_scope="local:alice",
        available=unrestricted.available,
        unavailable=(),
        selected=unrestricted.selected,
        usable_profile_aliases=((PluginId("transform", "llm"), ("text-model",)),),
        selected_profile_aliases=(),
        binding_generation_fingerprint="template-route-profile-generation",
    )
    app.state.settings = settings
    app.state.catalog_service = catalog
    app.state.operator_profile_registry = OperatorProfileRegistry(policy=policy, settings=runtime)
    app.state.plugin_snapshot_factory = StaticPluginSnapshotFactory(snapshot)
    return app, sessions


def _llm_options(template: str) -> dict[str, Any]:
    return {
        "profile": "text-model",
        "system_prompt": "You rate short texts.",
        "required_input_fields": [],
        "schema": {"mode": "observed"},
        "queries": {"q1": {"input_fields": {"c": "text"}, "output_fields": _QUERY_OUTPUTS, "template": template}},
    }


def _pipeline_yaml(template: str) -> str:
    """One llm step, as pasted: a csv source with no path, a sink under outputs/."""
    pipeline = {
        "sources": {
            "source": {
                "plugin": "csv",
                "on_success": "rows",
                "options": {"schema": {"mode": "flexible", "fields": ["text: str"]}},
                "on_validation_failure": "discard",
            }
        },
        "transforms": [
            {
                "name": "classify",
                "plugin": "llm",
                "input": "rows",
                "on_success": "results",
                "on_error": "discard",
                "options": _llm_options(template),
            }
        ],
        "sinks": {
            "results": {
                "plugin": "json",
                "on_write_failure": "discard",
                "options": {"path": "outputs/out.jsonl", "format": "jsonl", "schema": {"mode": "observed"}},
            }
        },
    }
    return yaml.safe_dump(pipeline, sort_keys=False)


def _older_saved_state(template: str) -> CompositionStateData:
    """The same pipeline built in code and written straight to the store: no tool, no import."""
    state = CompositionState(
        source=SourceSpec(
            plugin="csv",
            on_success="rows",
            options={"schema": {"mode": "flexible", "fields": ["text: str"]}},
            on_validation_failure="discard",
        ),
        nodes=(
            NodeSpec(
                id="classify",
                node_type="transform",
                plugin="llm",
                input="rows",
                on_success="results",
                on_error="discard",
                options=_llm_options(template),
                condition=None,
                routes=None,
                fork_to=None,
                branches=None,
                policy=None,
                merge=None,
            ),
        ),
        edges=(),
        outputs=(
            OutputSpec(
                name="results",
                plugin="json",
                options={"path": "outputs/out.jsonl", "format": "jsonl", "schema": {"mode": "observed"}},
                on_write_failure="discard",
            ),
        ),
        metadata=PipelineMetadata(),
        version=1,
    )
    payload = state.to_dict()
    return CompositionStateData(
        sources=payload["sources"],
        nodes=payload["nodes"],
        edges=payload["edges"],
        outputs=payload["outputs"],
        metadata_=payload["metadata"],
        is_valid=False,
    )


async def _saved_session(tmp_path: Path, template: str, origin: str) -> tuple[Any, Any, Any]:
    app, sessions = _profile_app(tmp_path)
    session = await sessions.create_session("alice", "Saved text", "local")
    if origin == "yaml-import":
        imported = SyncASGITestClient(app).post(f"/api/sessions/{session.id}/state/yaml", json={"yaml": _pipeline_yaml(template)})
        assert imported.status_code == 200, imported.text
    else:
        await _save_test_composition_state(sessions, session.id, _older_saved_state(template), provenance="session_seed")
    return app, sessions, session


ORIGINS = ["yaml-import", "older-saved-state"]


@pytest.mark.asyncio
@pytest.mark.parametrize("origin", ORIGINS)
@pytest.mark.parametrize("name", INPUTS)
async def test_the_saved_state_reads_back_with_an_entry_naming_the_step(tmp_path: Path, name: str, origin: str) -> None:
    template, expected = INPUTS[name]
    app, _sessions, session = await _saved_session(tmp_path, template, origin)

    read = SyncASGITestClient(app).get(f"/api/sessions/{session.id}/state")

    assert read.status_code == 200, read.text[:500]
    body = read.json()
    assert body["is_valid"] is False
    if origin == "older-saved-state":
        # GET state shows the errors stored with the record (none were stored here,
        # as for a state older code saved) and re-runs validation only for its
        # warnings and suggestions: that re-run is what raised before. The fresh
        # entry reaches the model on the next turn (the turn test below).
        assert body["validation_errors"] is None
        return
    entries = [(entry["component"], entry["message"]) for entry in body["validation_errors"]]
    assert any(component == "node:classify" and message.startswith(expected) for component, message in entries), entries


@pytest.mark.asyncio
@pytest.mark.parametrize("origin", ORIGINS)
@pytest.mark.parametrize("name", INPUTS)
async def test_a_composer_turn_on_the_saved_state_ends_normally(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, name: str, origin: str
) -> None:
    from elspeth.web.composer.availability import ComposerAvailability
    from elspeth.web.composer.service import ComposerServiceImpl

    template, _expected = INPUTS[name]
    app, sessions, session = await _saved_session(tmp_path, template, origin)
    planner_calls: list[dict[str, Any]] = []
    end_checks: list[dict[str, Any]] = []

    async def provider(**kwargs: Any) -> Any:
        if "response_format" in kwargs:
            end_checks.append(kwargs)
            verdict = {"verdict": "CLEAN", "category": "other", "steps": [], "findings": "", "note": None, "publication_verdict": "ADMIT"}
            return audited_response(content=json.dumps(verdict))
        planner_calls.append(kwargs)
        return audited_response(content="The saved pipeline is unchanged.")

    monkeypatch.setattr("litellm.acompletion", provider)
    monkeypatch.setattr(
        "elspeth.web.composer.service.compute_availability",
        lambda **kwargs: ComposerAvailability(available=True, provider="test", model=kwargs["model"]),
    )
    app.state.composer_service = ComposerServiceImpl.for_trained_operator(
        catalog=app.state.catalog_service,
        settings=app.state.settings,
        sessions_service=sessions,
        session_engine=app.state.session_engine,
    )

    async with _running_job(app, sessions, session.id, kind="compose_message", content="Check the saved pipeline.") as job:
        completed = await _run(app, job)

    assert completed.status == "completed", completed
    assert planner_calls, "the planner was reached"
    assert len(end_checks) == 1, "the real end-of-turn checkpoint ran"
    sent = json.dumps(end_checks[0]["messages"])
    assert (UNKNOWN_LINE in sent) is (name != "nested-loops")
    told = json.dumps(planner_calls[0]["messages"])
    assert _expected in told, told[:3000]
    at = told.index(_expected)
    assert "classify" in told[max(0, at - 200) : at], told[max(0, at - 400) : at + 200]
