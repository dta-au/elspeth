"""Template text nested too deeply is refused in a typed way, never with a builtin error.

Two shapes pass every source bound in a few hundred bytes:

- more than 20 nested loops: Jinja's generated code is refused by Python's own
  compiler with a builtin ``SyntaxError``, which no template validator caught;
- a deep expression chain: the field analysis recursed until ``RecursionError``
  wherever it ran without the sandbox's depth bound first.

Inputs are generated by loops. Expected texts are spelled here and new types
are imported inside the tests, so the file collects on the tree before the change.
"""

from __future__ import annotations

from collections.abc import Callable

import pytest

from elspeth.core import templates
from elspeth.plugins.infrastructure.templates import TemplateError, create_sandboxed_environment


def _nested_loops(levels: int) -> str:
    return "Rate {{ row.review }}. " + "{% for item in [1] %}" * levels + "x" + "{% endfor %}" * levels


DEEP_SHAPES: dict[str, Callable[[int], str]] = {
    "arithmetic-chain": lambda n: "{{ 1" + "+1" * n + " }}",
    "attribute-chain": lambda n: "{{ row" + ".a" * n + " }}",
    "filter-chain": lambda n: "{{ row.a" + "|trim" * n + " }}",
    "unary-chain": lambda n: "{{ " + "not " * n + "row.a }}",
    "nested-literal": lambda n: "{{ " + "{1:" * n + "1" + "}" * n + " }}",
}

ANALYSES: dict[str, Callable[[str], object]] = {
    "field-usage": templates.extract_jinja2_field_usage,
    "fields": templates.extract_jinja2_fields,
    "context-fields": lambda text: templates.extract_jinja2_context_fields(text, row_attribute="source_row"),
    "loads-row": lambda text: templates.template_loads_name(text, "row"),
}


@pytest.fixture(autouse=True)
def _clear_analysis_caches() -> None:
    templates._cached_jinja2_field_usage.cache_clear()
    templates._cached_jinja2_context_fields.cache_clear()


def test_twenty_nested_loops_compile() -> None:
    create_sandboxed_environment().from_string(_nested_loops(20))


def test_twenty_one_nested_loops_are_a_template_error_not_a_builtin_syntax_error() -> None:
    with pytest.raises(TemplateError) as raised:
        create_sandboxed_environment().from_string(_nested_loops(21))

    from elspeth.plugins.infrastructure.templates import TemplateTooDeeplyNested

    assert type(raised.value) is TemplateTooDeeplyNested
    assert str(raised.value) == "Template blocks are too deeply nested to compile"
    assert type(raised.value.__cause__) is SyntaxError


@pytest.mark.parametrize("analysis", ANALYSES.values(), ids=ANALYSES.keys())
@pytest.mark.parametrize("shape", DEEP_SHAPES.values(), ids=DEEP_SHAPES.keys())
def test_analysis_of_deep_text_is_refused_as_a_value_error(shape: Callable[[int], str], analysis: Callable[[str], object]) -> None:
    text = shape(1500)
    templates.validate_jinja_source(text)  # far under every source bound

    with pytest.raises(ValueError, match="Template is too deeply nested to analyse") as raised:
        analysis(text)

    from elspeth.core.templates import TemplateSourceRefusedError, TemplateTooDeeplyNestedError

    assert type(raised.value) is TemplateTooDeeplyNestedError
    assert isinstance(raised.value, TemplateSourceRefusedError)


@pytest.mark.parametrize("shape", DEEP_SHAPES.values(), ids=DEEP_SHAPES.keys())
def test_analysis_refuses_nothing_the_sandbox_compiles(shape: Callable[[int], str]) -> None:
    """The analysis bound is the sandbox's own depth bound, measured the same way."""
    environment = create_sandboxed_environment()
    compiled = 0
    for n in range(1, 140):
        text = shape(n)
        try:
            environment.from_string(text)
        except TemplateError:
            continue
        compiled += 1
        templates.extract_jinja2_field_usage(text)
        templates.template_loads_name(text, "row")
    assert compiled >= 30  # control: the walk reached the depth where the bound bites


@pytest.mark.parametrize(
    "text",
    [
        pytest.param("{{ row.name }}" * 257, id="expression-count"),
        pytest.param("(" * 65 + "x" + ")" * 65, id="bracket-nesting"),
    ],
)
def test_every_source_refusal_shares_one_owned_type(text: str) -> None:
    """The advisor summary catches this one type; a plain ValueError here would escape it again."""
    with pytest.raises(ValueError) as raised:
        templates.validate_jinja_source(text)

    from elspeth.core.templates import TemplateSourceRefusedError

    assert isinstance(raised.value, TemplateSourceRefusedError)
